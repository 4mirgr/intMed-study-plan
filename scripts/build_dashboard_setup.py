"""Bundle the owner-only, one-time SQL setup; no private credentials are used."""
from pathlib import Path
import argparse
root = Path(__file__).resolve().parents[1] / 'backend' / 'supabase'
parts = ['dashboard_upgrade.sql', 'rename_owner_drgerami.sql', 'telegram_notifications.sql']
header = '-- Generated by scripts/build_dashboard_setup.py. Run once in Supabase SQL Editor.\n-- Preserves existing UUIDs and study data; renames only the single verified active admin.\n-- Bot token belongs in Edge secrets, never here.\n\n'
content = header + '\n\n'.join('-- Source: ' + name + '\n' + (root / name).read_text() for name in parts)
args = argparse.ArgumentParser()
args.add_argument('--check', action='store_true')
options = args.parse_args()
target = root / 'setup_dashboard.sql'
if options.check:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('Run python3 scripts/build_dashboard_setup.py before publishing SQL changes')
    print('Dashboard setup SQL is current.')
else:
    target.write_text(content)
    print('Built the one-time dashboard SQL setup.')
